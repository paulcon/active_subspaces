"""Regenerate ``src/active_subspaces/_reference_data.py`` (spec 12 §3.4, §5.7) [D-126].

For each engineering test function: ``M = 10**6`` normalized points from
``space.sample(M, rng=2016, normalized=True)``, physical gradients from
``evaluate_with_grads(..., batch_size=10**5)``, mapped to normalized
coordinates; ``C = G^T G / M`` is diagonalized with ``np.linalg.eigh``, the
eigenvector sign rule of spec 07 (largest-magnitude entry positive) is
applied, and the eigenvalues and their delta-method standard errors are the
means and standard errors (ddof 1) of ``s_ik = (w_k^T g_i)^2``. The mean and
variance of ``f`` come from the same sample.

Usage (from the repository root)::

    python tools/make_reference_results.py            # write the data module
    python tools/make_reference_results.py --check    # compare fields with the stored module

Rerun when a test function or the sign rule changes, and review the diff.
"""

from __future__ import annotations

import argparse
import os
import pprint
import sys

import numpy as np

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_SRC = os.path.join(_ROOT, "src")
if _SRC not in sys.path:
    sys.path.insert(0, _SRC)

from active_subspaces import _random
from active_subspaces.models import ReferenceResults, evaluate_with_grads
from active_subspaces.results import _make_provenance
from active_subspaces.spaces import _orient_columns

N_SAMPLES = 10**6
SEED = 2016
BATCH_SIZE = 10**5
NAMES = ("borehole", "otl_circuit", "piston", "robot_arm", "wing_weight")
OUTPUT = os.path.join(_SRC, "active_subspaces", "_reference_data.py")


def reference_results(model, n_samples: int = N_SAMPLES, seed: int = SEED) -> ReferenceResults:
    """Monte Carlo reference results of one model (spec 12 §3.4)."""
    space = model.space
    M = int(n_samples)
    Xn = space.sample(M, rng=seed, normalized=True)
    X = space.from_normalized(Xn)
    f, G = evaluate_with_grads(model, X=X, batch_size=min(BATCH_SIZE, M))
    g = space.grads_to_normalized(G)
    C = g.T @ g / M
    _, W = np.linalg.eigh(C)
    W = _orient_columns(W[:, ::-1])
    S = (g @ W) ** 2
    lam = S.mean(axis=0)
    se = S.std(axis=0, ddof=1) / np.sqrt(M)
    _, rng_desc = _random.generator(seed)
    prov = _make_provenance(
        "evaluate_with_grads",
        {
            "model": model.name,
            "batch_size": min(BATCH_SIZE, M),
            "n_samples": M,
            "generator": "tools/make_reference_results.py",
        },
        space=space,
        rng_state=rng_desc,
    )
    return ReferenceResults(
        model=model.name,
        exact=False,
        eigenvalues=lam,
        eigenvectors=W,
        eigenvalue_se=se,
        mean=float(np.mean(f)),
        mean_se=float(np.std(f, ddof=1) / np.sqrt(M)),
        variance=float(np.var(f, ddof=1)),
        n_samples=M,
        seed=seed,
        qoi=model.qoi,
        provenance=prov,
    )


def compute(n_samples: int = N_SAMPLES) -> dict[str, dict]:
    """``{name: ReferenceResults.to_dict()}`` for the five engineering functions."""
    from active_subspaces import test_functions as tf

    models = {m.name: m for m in (tf.BOREHOLE, tf.OTL_CIRCUIT, tf.PISTON, tf.ROBOT_ARM, tf.WING_WEIGHT)}
    return {name: reference_results(models[name], n_samples).to_dict() for name in NAMES}


def render(data: dict[str, dict], n_samples: int) -> str:
    """The text of the generated module; floats are written by ``repr`` and decode exactly."""
    body = pprint.pformat(data, width=110, sort_dicts=True)
    return (
        '"""Stored reference results of the engineering test functions (spec 12 §3.4, §5.7).\n\n'
        "Generated by tools/make_reference_results.py; do not edit. Each entry is\n"
        "``ReferenceResults.to_dict()``: Monte Carlo with N_SAMPLES points, seed 2016.\n"
        '"""\n\n'
        "__all__ = ()\n\n"
        f"N_SAMPLES = {int(n_samples)}\n\n"
        f"REFERENCE_RESULTS: dict = {body}\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare the computed fields with the stored module")
    parser.add_argument("--n-samples", type=int, default=N_SAMPLES)
    parser.add_argument("--output", default=OUTPUT)
    args = parser.parse_args(argv)
    data = compute(args.n_samples)
    if args.check:
        from active_subspaces import _reference_data

        stored = _reference_data.REFERENCE_RESULTS
        bad = [n for n in NAMES if n not in stored or stored[n]["fields"] != data[n]["fields"]]
        print("reference results match" if not bad else f"reference results differ: {bad}")
        return 1 if bad else 0
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(render(data, args.n_samples))
    print(f"wrote {args.output} (M = {args.n_samples})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
